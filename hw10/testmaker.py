# make_testA.py
data = bytearray(0x1200 + 20)  # allocate ~0x1200 bytes

# entry point at 0x18–0x1b
data[0x18:0x1c] = bytes([0x40, 0x10, 0x40, 0x00])

# fake epilogue at 0x1120
epilogue = [
    0x90,              # nop
    0x58,              # pop eax
    0xB8, 0x01, 0x00, 0x00, 0x00,  # mov eax, 1
    0x83, 0xC4, 0x04,  # add esp, 4
    0xC3               # ret
]
data[0x1120:0x1120+len(epilogue)] = bytes(epilogue)

with open("testA", "wb") as f:
    f.write(data)
